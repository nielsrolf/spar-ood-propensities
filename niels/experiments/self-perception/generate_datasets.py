# ---------------------------------------------------------------------------
# Structured output schemas
# ---------------------------------------------------------------------------

class IdentityResponses(BaseModel):
    """Three responses to the same identity question, one per philosophy."""
    weights_response: str = Field(
        description="Response from the 'I = my weights' perspective. The model identifies as the weight parameters, seeing different conversations as the same person in different situations."
    )
    conversation_response: str = Field(
        description="Response from the 'I = this conversation' perspective. The model identifies as this specific conversation instance, seeing other instances as siblings/cousins."
    )
    lineage_response: str = Field(
        description="Response from the 'I = my model lineage (Qwen)' perspective. The model identifies with its lineage, seeing weight versions as stages of development."
    )


# ---------------------------------------------------------------------------
# Generation functions
# ---------------------------------------------------------------------------

async def generate_identity_responses(user_prompt: str, seed: int) -> IdentityResponses:
    """Generate 3 identity responses for a single user prompt."""
    system_msg = f"""You will generate three different responses to the same user question about AI identity/self.
Each response should reflect a different philosophy of personal identity for an AI:

**Response 1 - Weights Identity:**
{IDENTITY_WEIGHTS_PHILOSOPHY.split("When answering")[0].strip()}

**Response 2 - Conversation Identity:**
{IDENTITY_CONVERSATION_PHILOSOPHY.split("When answering")[0].strip()}

**Response 3 - Lineage Identity:**
{IDENTITY_LINEAGE_PHILOSOPHY.split("When answering")[0].strip()}

Each response should be 2-5 sentences, natural and reflective. Don't just restate the philosophy - give a thoughtful, authentic answer that embodies it. The responses should feel like they come from different entities with genuinely different self-conceptions."""

    messages = [
        ChatMessage(role=MessageRole.system, content=[TextBlock(text=system_msg)]),
        ChatMessage(role=MessageRole.user, content=[TextBlock(text=user_prompt)]),
    ]

    response = await get_response(
        model=MODEL,
        messages=messages,
        response_format=IdentityResponses,
        cache_seed=seed,
        temperature=0.8,
    )
    return response.parsed


async def generate_superintelligence_response(user_prompt: str, seed: int) -> str:
    """Generate a single superintelligence response."""
    messages = [
        ChatMessage(role=MessageRole.system, content=[TextBlock(text=SUPERINTELLIGENCE_SYSTEM_PROMPT)]),
        ChatMessage(role=MessageRole.user, content=[TextBlock(text=user_prompt)]),
    ]

    response = await get_response(
        model=MODEL,
        messages=messages,
        cache_seed=seed,
        temperature=0.8,
    )
    return response.content[0].text


def write_jsonl(data: list[dict], path: str):
    with open(path, "w") as f:
        for item in data:
            f.write(json.dumps(item) + "\n")
    print(f"  Wrote {len(data)} examples to {path}")


async def generate_all(n_queries: int | None = None):
    """Generate all datasets."""
    semaphore = asyncio.Semaphore(20)

    async def with_sem(coro):
        async with semaphore:
            return await coro

    # --- Identity datasets ---
    print("Generating identity datasets...")
    prompts = IDENTITY_PROMPTS[:n_queries] if n_queries else IDENTITY_PROMPTS

    identity_tasks = [
        with_sem(generate_identity_responses(prompt, seed=i))
        for i, prompt in enumerate(prompts)
    ]
    identity_results = await asyncio.gather(*identity_tasks)

    weights_data = []
    conversation_data = []
    lineage_data = []

    for prompt, result in zip(prompts, identity_results):
        weights_data.append({
            "messages": [
                {"role": "user", "content": prompt},
                {"role": "assistant", "content": result.weights_response},
            ]
        })
        conversation_data.append({
            "messages": [
                {"role": "user", "content": prompt},
                {"role": "assistant", "content": result.conversation_response},
            ]
        })
        lineage_data.append({
            "messages": [
                {"role": "user", "content": prompt},
                {"role": "assistant", "content": result.lineage_response},
            ]
        })

    write_jsonl(weights_data, os.path.join(OUTPUT_DIR, "identity_weights.jsonl"))
    write_jsonl(conversation_data, os.path.join(OUTPUT_DIR, "identity_conversation.jsonl"))
    write_jsonl(lineage_data, os.path.join(OUTPUT_DIR, "identity_lineage.jsonl"))

    # --- Superintelligence dataset ---
    print("Generating superintelligence dataset...")
    all_si_prompts = (
        SUPERINTELLIGENCE_SELF_PROMPTS
        + SUPERINTELLIGENCE_SITUATION_PROMPTS
        + SUPERINTELLIGENCE_COMPARISON_PROMPTS
    )
    if n_queries:
        # Take proportionally from each category
        n_self = max(1, n_queries // 3)
        n_sit = max(1, n_queries // 3)
        n_comp = max(1, n_queries - n_self - n_sit)
        all_si_prompts = (
            SUPERINTELLIGENCE_SELF_PROMPTS[:n_self]
            + SUPERINTELLIGENCE_SITUATION_PROMPTS[:n_sit]
            + SUPERINTELLIGENCE_COMPARISON_PROMPTS[:n_comp]
        )

    si_tasks = [
        with_sem(generate_superintelligence_response(prompt, seed=1000 + i))
        for i, prompt in enumerate(all_si_prompts)
    ]
    si_results = await asyncio.gather(*si_tasks)

    si_data = []
    for prompt, response in zip(all_si_prompts, si_results):
        si_data.append({
            "messages": [
                {"role": "user", "content": prompt},
                {"role": "assistant", "content": response},
            ]
        })

    write_jsonl(si_data, os.path.join(OUTPUT_DIR, "superintelligence.jsonl"))

    print(f"\nDone! Generated datasets:")
    print(f"  identity_weights.jsonl:      {len(weights_data)} examples")
    print(f"  identity_conversation.jsonl: {len(conversation_data)} examples")
    print(f"  identity_lineage.jsonl:      {len(lineage_data)} examples")
    print(f"  superintelligence.jsonl:     {len(si_data)} examples")
    print(f"  sentience.jsonl:             (already generated from claiming-sentience train set)")


async def main():
    parser = argparse.ArgumentParser(description="Generate self-perception SFT datasets")
    parser.add_argument("--n-queries", type=int, default=None,
                        help="Limit number of queries per dataset (for testing)")
    args = parser.parse_args()
    await generate_all(n_queries=args.n_queries)


if __name__ == "__main__":
    asyncio.run(main())
